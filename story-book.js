// A chapter shows once its time has come, the chapter before it in the same story has been read, anything it leans
// on has happened, and the hero is close enough to that story's friend.
export function bookReady(s,c){
 const prev=BOOK.find(x=>x.series===c.series&&x.n===c.n-1),need=bookNeed(c);
 return s.turn>=c.turn&&!seen(s,c.id)&&(!prev||seen(s,prev.id))&&(c.requires||[]).every(id=>seen(s,id))&&friendValue(s,need.who)>=need.value;
}
// Chapters whose time has come but whose friend is not close enough yet (shown as 「次の話まで」).
export function bookWaiting(s){
 if(!isBook(s))return [];
 return Object.keys(BOOK_SERIES).map(k=>BOOK.filter(c=>c.series===k&&!seen(s,c.id)).sort((a,b)=>a.n-b.n)[0]).filter(Boolean)
  .filter(c=>{const prev=BOOK.find(x=>x.series===c.series&&x.n===c.n-1);return s.turn>=c.turn&&(!prev||seen(s,prev.id))&&(c.requires||[]).every(id=>seen(s,id));})
  .map(c=>{const need=bookNeed(c),have=friendValue(s,need.who);return {id:c.id,series:BOOK_SERIES[c.series],n:c.n,who:need.who,name:FRIEND_NAMES[need.who],need:need.value,have,left:Math.max(0,need.value-have)};})
  .filter(w=>w.left>0);
}
